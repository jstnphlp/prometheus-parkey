import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { pathToFileURL, URL } from 'node:url'

import {
  validateSnapshotProvenance,
  validateOsmSnapshot,
} from './parking-import.mjs'

// Offline local seed only. Never connects to a database or publishes candidates.
export function renderOsmSeed(input, options) {
  const records = validateOsmSnapshot(input, options)
  const literal = (text) => "'" + text.replaceAll("'", "''") + "'"
  const payload = literal(JSON.stringify(records))
  const sourceId = 'd0000000-0000-4000-8000-000000000001'
  return `-- GENERATED by node scripts/osm-snapshot-sql.mjs. LOCAL DEVELOPMENT ONLY.
-- Real OSM snapshot, all records UNVERIFIED. ODbL-1.0; see docs/mobile-discovery.md.
-- Immutable replay: changed existing content requires explicit human reconciliation.
begin;
lock table public.discovery_sources, public.discovery_parking, public.discovery_regulations in share row exclusive mode;
create temporary table osm_snapshot on commit drop as
select value as record from jsonb_array_elements(${payload}::jsonb);
create temporary table osm_expected on commit drop as
select record->>'id' as source_record_id, record->>'sourceUrl' as source_url,
 (record->>'sourceUpdatedAt')::timestamptz as source_updated_at,
 record->>'name' as name, record->>'kind' as kind,
 extensions.st_setsrid(extensions.st_geomfromgeojson((record->'geometry')::text),4326) as geometry,
 record->>'side' as side, record->>'address' as address,
 record->>'fees' as fees, record->>'hours' as hours,
 coalesce(record->'osmTags','{}'::jsonb) as osm_tags,
 (record->>'osmEditedAt')::timestamptz as osm_edited_at,
 coalesce(record->'entrances','[]'::jsonb) as entrances
from osm_snapshot;
create temporary table osm_expected_rules on commit drop as
select record->>'id' as source_record_id, rule->>'description' as description,
 rule->>'sourceUrl' as source_url, (rule->>'observedAt')::timestamptz as observed_at
from osm_snapshot cross join lateral jsonb_array_elements(record->'regulations') as rule;
do $guard$
begin
 if exists (select 1 from public.discovery_sources where id='${sourceId}' and
  (kind,label,url,license,attribution) is distinct from
  ('osm','© OpenStreetMap contributors · pilot snapshot','https://www.openstreetmap.org/copyright','ODbL-1.0','© OpenStreetMap contributors')) then
  raise exception 'OSM source attribution differs; reconcile manually before replay';
 end if;
 if exists (select 1 from public.discovery_parking p join osm_expected e using(source_record_id)
  where p.source_id='${sourceId}' and (
   (p.source_url,p.source_updated_at,p.name,p.kind,p.side,p.address,p.fees,p.hours,p.osm_tags,p.osm_edited_at,p.entrances)
    is distinct from (e.source_url,e.source_updated_at,e.name,e.kind,e.side,e.address,e.fees,e.hours,e.osm_tags,e.osm_edited_at,e.entrances)
   or extensions.st_asewkb(p.geometry) is distinct from extensions.st_asewkb(e.geometry)
   or p.verification <> 'unverified' or p.verified_at is not null or p.verification_url is not null or not p.published
  )) then
  raise exception 'Existing OSM record differs or was reviewed; reconcile manually before replay';
 end if;
 if exists (select 1 from public.discovery_parking p join osm_expected e using(source_record_id)
  where p.source_id='${sourceId}' and
   coalesce((select jsonb_agg(jsonb_build_array(r.description,r.source_url,r.observed_at,r.source_id,r.published)
    order by r.description,r.source_url,r.observed_at,r.source_id,r.published)
    from public.discovery_regulations r where r.parking_id=p.id),'[]'::jsonb)
   is distinct from
   coalesce((select jsonb_agg(jsonb_build_array(r.description,r.source_url,r.observed_at,'${sourceId}'::uuid,true)
    order by r.description,r.source_url,r.observed_at)
    from osm_expected_rules r where r.source_record_id=e.source_record_id),'[]'::jsonb)) then
  raise exception 'Existing OSM regulations differ; reconcile manually before replay';
 end if;
end;
$guard$;
insert into public.discovery_sources (id,kind,label,url,license,attribution)
values ('${sourceId}','osm','© OpenStreetMap contributors · pilot snapshot',
 'https://www.openstreetmap.org/copyright','ODbL-1.0','© OpenStreetMap contributors')
on conflict (id) do nothing;
insert into public.discovery_parking (
 source_id,source_record_id,source_url,source_updated_at,name,kind,geometry,
 side,address,fees,hours,verification,published,osm_tags,osm_edited_at,entrances
)
select '${sourceId}',source_record_id,source_url,source_updated_at,name,kind,geometry,
 side,address,fees,hours,'unverified',true,osm_tags,osm_edited_at,entrances
from osm_expected on conflict (source_id,source_record_id) do nothing;
insert into public.discovery_regulations (parking_id,source_id,description,source_url,observed_at,published)
select p.id,'${sourceId}',r.description,r.source_url,r.observed_at,true
from osm_expected_rules r
join public.discovery_parking p on p.source_id='${sourceId}' and p.source_record_id=r.source_record_id
where not exists (select 1 from public.discovery_regulations existing where existing.parking_id=p.id
 and (existing.source_id,existing.description,existing.source_url,existing.observed_at,existing.published)
 is not distinct from ('${sourceId}'::uuid,r.description,r.source_url,r.observed_at,true));
commit;
`
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const snapshotPath = new URL(
    '../apps/mobile/src/discovery/osm-pilot.json',
    import.meta.url,
  )
  const snapshotBytes = readFileSync(snapshotPath)
  const records = JSON.parse(snapshotBytes.toString('utf8'))
  const manifestPath = new URL(
    '../apps/mobile/src/discovery/osm-pilot.json.manifest.json',
    import.meta.url,
  )
  validateSnapshotProvenance(
    snapshotBytes,
    records,
    existsSync(manifestPath)
      ? JSON.parse(readFileSync(manifestPath, 'utf8'))
      : undefined,
  )
  const sql = renderOsmSeed(records)
  const target = new URL('../supabase/seed-discovery.sql', import.meta.url)
  if (process.argv.slice(2).some((arg) => arg !== '--check'))
    throw new Error('Usage: node scripts/osm-snapshot-sql.mjs [--check]')
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== sql)
      throw new Error(
        'Discovery seed is stale. Run node scripts/osm-snapshot-sql.mjs.',
      )
  } else writeFileSync(target, sql)
  process.stdout.write(
    `Validated local discovery seed for ${records.length} OSM records\n`,
  )
}
